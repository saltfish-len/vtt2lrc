/** 日志行的语义色，不属于 M3 配色表，单独通过 CompositionLocal 下发。 */
data class LogColors(val success: Color, val warn: Color)

val LocalLogColors = staticCompositionLocalOf {
    LogColors(success = LogSuccessLight, warn = LogWarnLight)
}

@Composable
fun Vtt2lrcTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // 壁纸取色会盖掉品牌配色，默认关闭；需要跟随系统时传 true
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val logColors = if (darkTheme) {
        LogColors(success = LogSuccessDark, warn = LogWarnDark)
    } else {
        LogColors(success = LogSuccessLight, warn = LogWarnLight)
    }

    CompositionLocalProvider(LocalLogColors provides logColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
